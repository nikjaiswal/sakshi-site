#!/usr/bin/env python3
"""Generate the dot-matrix world map used on the home page.

Usage: python3 tools/make-world-map.py path/to/ne_110m_land.geojson > content/partials/world-dots.svg

Input: Natural Earth 1:110m land polygons (public domain), for example
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
Output: an SVG fragment with one <path> of zero-length subpaths on a 2.4
degree grid (rendered as dots by a round stroke cap), in an equirectangular
projection on a 1000 x 394 canvas (longitude -180..180, latitude 84..-58).
No dependencies beyond the standard library.
"""
import json, sys

W = 1000.0
LAT_TOP, LAT_BOTTOM = 84.0, -58.0
SCALE = W / 360.0
H = (LAT_TOP - LAT_BOTTOM) * SCALE
STEP = 2.4

def project(lon, lat):
    return (lon + 180.0) * SCALE, (LAT_TOP - lat) * SCALE

def inside(ring, x, y):
    n = len(ring); j = n - 1; res = False
    for i in range(n):
        xi, yi = ring[i]; xj, yj = ring[j]
        if ((yi > y) != (yj > y)) and (x < (xj - xi) * (y - yi) / ((yj - yi) or 1e-12) + xi):
            res = not res
        j = i
    return res

def in_polygon(poly, x, y):
    if not inside(poly[0], x, y):
        return False
    return not any(inside(hole, x, y) for hole in poly[1:])

def main():
    data = json.load(open(sys.argv[1]))
    polys = []
    for f in data["features"]:
        g = f["geometry"]
        if g["type"] == "Polygon":
            polys.append(g["coordinates"])
        elif g["type"] == "MultiPolygon":
            polys.extend(g["coordinates"])
    # bounding boxes for a quick reject
    boxed = []
    for p in polys:
        xs = [pt[0] for pt in p[0]]; ys = [pt[1] for pt in p[0]]
        boxed.append((min(xs), max(xs), min(ys), max(ys), p))
    out = []
    row = 0
    lat = LAT_TOP - 1.0
    while lat > LAT_BOTTOM:
        offset = STEP / 2 if row % 2 else 0.0
        lon = -180.0 + offset + 0.6
        while lon < 180.0:
            hit = False
            for (x0, x1, y0, y1, p) in boxed:
                if x0 <= lon <= x1 and y0 <= lat <= y1 and in_polygon(p, lon, lat):
                    hit = True; break
            if hit:
                x, y = project(lon, lat)
                out.append('M%d %dh0' % (round(x), round(y)))
            lon += STEP
        lat -= STEP; row += 1
    sys.stdout.write("<!-- Generated by tools/make-world-map.py from Natural Earth 110m land (public domain). %d dots. -->\n" % len(out))
    sys.stdout.write('<path class="world__dots" d="' + ''.join(out) + '"/>\n')

if __name__ == "__main__":
    main()
